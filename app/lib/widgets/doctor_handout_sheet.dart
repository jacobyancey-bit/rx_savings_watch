import 'package:flutter/foundation.dart';
import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:url_launcher/url_launcher.dart';
import '../models/drug.dart';
import '../services/web_push_service.dart';

class DoctorHandoutSheet extends StatelessWidget {
  final Drug drug;
  final String? selectedStrength;
  final Map<String, dynamic>? discountCard;

  const DoctorHandoutSheet({
    super.key,
    required this.drug,
    this.selectedStrength,
    this.discountCard,
  });

  static void show(
    BuildContext context,
    Drug drug, {
    String? selectedStrength,
    Map<String, dynamic>? discountCard,
  }) {
    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.transparent,
      builder: (_) => DoctorHandoutSheet(
        drug: drug,
        selectedStrength: selectedStrength,
        discountCard: discountCard,
      ),
    );
  }

  String get _displayDosage {
    final dose = (selectedStrength != null && selectedStrength!.isNotEmpty)
        ? selectedStrength!
        : (drug.strength ?? '');
    final form = drug.dosageForm ?? '';
    if (dose.isNotEmpty && form.isNotEmpty) return '$dose • $form';
    return dose.isNotEmpty ? dose : form;
  }

  String get _ratingTitle {
    final isBiologic = drug.drugType == 'biologic';
    if (isBiologic) {
      return drug.biosimilarStatus == 'interchangeable'
          ? 'FDA Interchangeable Biosimilar'
          : 'FDA Biosimilar Status';
    }
    return drug.teCode != null
        ? 'FDA Therapeutic Equivalence (TE): ${drug.teCode} Rated'
        : 'FDA Generic Substitution Status';
  }

  String _buildPlainTextNote() {
    final buf = StringBuffer()
      ..writeln('Rx Savings Watch — Pharmacist / Prescriber Note')
      ..writeln('----------------------------------------')
      ..writeln('Prescribed Brand: ${drug.displayName}')
      ..writeln('Generic Ingredient: ${drug.genericName}');
    if (_displayDosage.isNotEmpty) {
      buf.writeln('Dosage & Form: $_displayDosage');
    }
    buf
      ..writeln('NLM RxCUI: ${drug.rxcui}')
      ..writeln('Status: $_ratingTitle')
      ..writeln('Guidance: ${drug.substitutionPlainGuidance}');
    if (drug.verificationSources.isNotEmpty) {
      buf.writeln('Verified via: ${drug.verificationSources.join(', ')}');
    }
    if (discountCard != null) {
      buf
        ..writeln('')
        ..writeln('Pharmacy Discount Card (${discountCard!['name'] ?? 'Rx Savings'})')
        ..writeln('BIN: ${discountCard!['bin']}  |  GROUP: ${discountCard!['group']}')
        ..writeln('PCN: ${discountCard!['pcn'] ?? '-'}  |  MEMBER ID: ${discountCard!['member_id']}');
    }
    buf.writeln('\nFor informational discussion with your doctor or pharmacist.');
    return buf.toString();
  }

  String _escapeHtml(String input) {
    return input
        .replaceAll('&', '&amp;')
        .replaceAll('<', '&lt;')
        .replaceAll('>', '&gt;')
        .replaceAll('"', '&quot;');
  }

  String _buildPrintableHtml() {
    final sources = drug.verificationSources.isNotEmpty
        ? '<div class="row"><span class="label">Official Sources:</span> ${_escapeHtml(drug.verificationSources.join(' • '))}</div>'
        : '';
    final dosageRow = _displayDosage.isNotEmpty
        ? '<div class="row"><span class="label">Dosage &amp; Form:</span> ${_escapeHtml(_displayDosage)}</div>'
        : '';

    final discountHtml = discountCard != null
        ? '''
      <div class="box">
        <div class="row"><span class="label">${_escapeHtml(discountCard!['name']?.toString() ?? 'Pharmacy Discount Card')}</span></div>
        <div class="row"><span class="label">BIN:</span> ${_escapeHtml(discountCard!['bin']?.toString() ?? '')} &nbsp;&nbsp; <span class="label">PCN:</span> ${_escapeHtml(discountCard!['pcn']?.toString() ?? '-')}</div>
        <div class="row"><span class="label">GROUP:</span> ${_escapeHtml(discountCard!['group']?.toString() ?? '')} &nbsp;&nbsp; <span class="label">MEMBER ID:</span> ${_escapeHtml(discountCard!['member_id']?.toString() ?? '')}</div>
      </div>'''
        : '';

    return '''
      <h1>Rx Savings Watch — Pharmacist &amp; Doctor Card</h1>
      <p class="sub">Bring or show this sheet at your pharmacy counter or doctor visit.</p>
      <div class="box">
        <div class="row"><span class="label">Prescribed Brand:</span> ${_escapeHtml(drug.displayName)}</div>
        <div class="row"><span class="label">Generic Ingredient:</span> ${_escapeHtml(drug.genericName)}</div>
        $dosageRow
        <div class="row"><span class="label">NLM RxCUI:</span> ${_escapeHtml(drug.rxcui)}</div>
        $sources
      </div>
      $discountHtml
      <div class="note">
        <div class="row"><span class="label">${_escapeHtml(_ratingTitle)}</span></div>
        <div>${_escapeHtml(drug.substitutionPlainGuidance)}</div>
      </div>
      <p class="disc">
        <strong>Medical Disclaimer:</strong> Generated by Rx Savings Watch (https://rx.dangling-dice-studios.com)
        from public FDA, NLM RxNorm, and CMS NADAC datasets for informational purposes only.
        Always confirm any substitution with your licensed pharmacist or prescribing physician.
      </p>
    ''';
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final isDark = theme.brightness == Brightness.dark;

    return Container(
      decoration: BoxDecoration(
        color: theme.colorScheme.surface,
        borderRadius: const BorderRadius.vertical(top: Radius.circular(24)),
      ),
      padding: const EdgeInsets.fromLTRB(24, 16, 24, 28),
      child: SingleChildScrollView(
        child: Column(
          mainAxisSize: MainAxisSize.min,
          crossAxisAlignment: CrossAxisAlignment.start,
          children: [
            Center(
              child: Container(
                width: 40,
                height: 4,
                decoration: BoxDecoration(
                  color: Colors.grey.shade400,
                  borderRadius: BorderRadius.circular(2),
                ),
              ),
            ),
            const SizedBox(height: 16),

            // Header
            Row(
              children: [
                Container(
                  padding: const EdgeInsets.all(10),
                  decoration: BoxDecoration(
                    color: Colors.teal.withValues(alpha: isDark ? 0.2 : 0.1),
                    borderRadius: BorderRadius.circular(12),
                  ),
                  child: Icon(
                    Icons.medical_services_outlined,
                    color: isDark ? Colors.teal.shade200 : Colors.teal.shade800,
                  ),
                ),
                const SizedBox(width: 12),
                Expanded(
                  child: Column(
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Text(
                        'Clinical Substitution Note',
                        style: TextStyle(
                          fontSize: 12,
                          fontWeight: FontWeight.bold,
                          color: isDark ? Colors.teal.shade200 : Colors.teal.shade800,
                          letterSpacing: 0.5,
                        ),
                      ),
                      Text(
                        'For Prescriber or Pharmacist',
                        style: theme.textTheme.titleMedium?.copyWith(
                          fontWeight: FontWeight.bold,
                        ),
                      ),
                    ],
                  ),
                ),
              ],
            ),

            const SizedBox(height: 18),

            // Drug details box
            Container(
              padding: const EdgeInsets.all(16),
              decoration: BoxDecoration(
                color: theme.colorScheme.surfaceContainerLow,
                borderRadius: BorderRadius.circular(14),
                border: Border.all(color: theme.colorScheme.outlineVariant),
              ),
              child: Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  _buildInfoRow(context, 'Prescribed Brand:', drug.displayName),
                  const SizedBox(height: 8),
                  _buildInfoRow(context, 'Generic Ingredient:', drug.genericName),
                  if (_displayDosage.isNotEmpty) ...[
                    const SizedBox(height: 8),
                    _buildInfoRow(context, 'Dosage & Form:', _displayDosage),
                  ],
                  const SizedBox(height: 8),
                  _buildInfoRow(context, 'Concept RxCUI:', drug.rxcui),
                ],
              ),
            ),

            const SizedBox(height: 14),

            // Therapeutic Equivalence / Biosimilarity Rating
            Container(
              padding: const EdgeInsets.all(14),
              decoration: BoxDecoration(
                color: Colors.teal.withValues(alpha: isDark ? 0.16 : 0.08),
                borderRadius: BorderRadius.circular(12),
                border: Border.all(
                  color: Colors.teal.withValues(alpha: isDark ? 0.4 : 0.3),
                ),
              ),
              child: Row(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Icon(
                    Icons.verified_outlined,
                    color: isDark ? Colors.teal.shade200 : Colors.teal.shade800,
                    size: 20,
                  ),
                  const SizedBox(width: 10),
                  Expanded(
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.start,
                      children: [
                        Text(
                          _ratingTitle,
                          style: TextStyle(
                            fontWeight: FontWeight.bold,
                            fontSize: 13.5,
                            color: theme.colorScheme.onSurface,
                          ),
                        ),
                        const SizedBox(height: 4),
                        Text(
                          drug.substitutionPlainGuidance,
                          style: TextStyle(
                            fontSize: 12.5,
                            color: theme.colorScheme.onSurface,
                            height: 1.35,
                          ),
                        ),
                      ],
                    ),
                  ),
                ],
              ),
            ),

            const SizedBox(height: 18),

            // Print / Send to Phone / Email / Copy Actions
            Wrap(
              spacing: 10,
              runSpacing: 10,
              children: [
                if (kIsWeb)
                  FilledButton.tonalIcon(
                    onPressed: () {
                      final ok = WebPushService.printHandout(
                        '${drug.displayName} — Pharmacist Card',
                        _buildPrintableHtml(),
                      );
                      if (!ok && context.mounted) {
                        ScaffoldMessenger.of(context).showSnackBar(
                          const SnackBar(content: Text('Allow pop-ups in your browser to print this card.')),
                        );
                      }
                    },
                    icon: const Icon(Icons.print_outlined, size: 18),
                    label: const Text('Print Card'),
                    style: FilledButton.styleFrom(minimumSize: const Size(0, 48)),
                  ),
                OutlinedButton.icon(
                  onPressed: () async {
                    final uri = Uri(
                      scheme: 'sms',
                      queryParameters: {'body': _buildPlainTextNote()},
                    );
                    final ok = await launchUrl(uri);
                    if (!ok && context.mounted) {
                      await Clipboard.setData(ClipboardData(text: _buildPlainTextNote()));
                      if (context.mounted) {
                        ScaffoldMessenger.of(context).showSnackBar(
                          const SnackBar(content: Text('Copied card text — paste into a text message to your phone.')),
                        );
                      }
                    }
                  },
                  icon: const Icon(Icons.sms_outlined, size: 18),
                  label: const Text('Text to Phone'),
                  style: OutlinedButton.styleFrom(minimumSize: const Size(0, 48)),
                ),
                OutlinedButton.icon(
                  onPressed: () async {
                    final uri = Uri(
                      scheme: 'mailto',
                      queryParameters: {
                        'subject': 'Pharmacist Note: ${drug.displayName}',
                        'body': _buildPlainTextNote(),
                      },
                    );
                    await launchUrl(uri);
                  },
                  icon: const Icon(Icons.email_outlined, size: 18),
                  label: const Text('Email Card'),
                  style: OutlinedButton.styleFrom(minimumSize: const Size(0, 48)),
                ),
                OutlinedButton.icon(
                  onPressed: () async {
                    await Clipboard.setData(ClipboardData(text: _buildPlainTextNote()));
                    if (context.mounted) {
                      ScaffoldMessenger.of(context).showSnackBar(
                        const SnackBar(content: Text('Pharmacist card copied to clipboard')),
                      );
                    }
                  },
                  icon: const Icon(Icons.copy_outlined, size: 18),
                  label: const Text('Copy Text'),
                  style: OutlinedButton.styleFrom(minimumSize: const Size(0, 48)),
                ),
              ],
            ),

            const SizedBox(height: 16),

            SizedBox(
              width: double.infinity,
              height: 50,
              child: FilledButton.icon(
                onPressed: () => Navigator.of(context).pop(),
                icon: const Icon(Icons.check),
                label: const Text('Done', style: TextStyle(fontSize: 16, fontWeight: FontWeight.bold)),
              ),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildInfoRow(BuildContext context, String label, String value) {
    final theme = Theme.of(context);
    return Row(
      crossAxisAlignment: CrossAxisAlignment.start,
      children: [
        SizedBox(
          width: 135,
          child: Text(
            label,
            style: TextStyle(fontSize: 13, color: theme.colorScheme.onSurfaceVariant),
          ),
        ),
        Expanded(
          child: Text(
            value,
            style: TextStyle(
              fontSize: 13.5,
              fontWeight: FontWeight.bold,
              color: theme.colorScheme.onSurface,
            ),
          ),
        ),
      ],
    );
  }
}
